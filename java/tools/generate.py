# ------------------------------------------------------------------ text helpers

def ascii_text(s: str) -> str:
    s = s.replace("\u2014", " - ").replace("\u2013", "-").replace("\u2018", "'").replace("\u2019", "'")
    s = s.replace("“", '"').replace("”", '"').replace("§", "section ").replace("…", "...")
    out = []
    for ch in s:
        if ord(ch) < 128:
            out.append(ch)
        else:
            d = unicodedata.normalize("NFKD", ch).encode("ascii", "ignore").decode()
            out.append(d if d else "?")
    return "".join(out)


def jd(text: str | None, limit: int = 420) -> str:
    """Javadoc-safe first paragraph."""
    if not text:
        return ""
    t = ascii_text(text).strip().split("\n\n")[0]
    t = re.sub(r"\s+", " ", t)
    if len(t) > limit:
        cut = t[:limit]
        idx = max(cut.rfind(". "), cut.rfind("; "))
        t = (cut[: idx + 1] if idx > 120 else cut.rstrip() + "...")
    t = t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("@", "&#64;")
    t = t.replace("\\", "&#92;").replace("*/", "*&#47;").replace("{", "&#123;").replace("}", "&#125;")
    t = re.sub(r"`([^`]*)`", r"<code>\1</code>", t)
    t = t.replace("`", "")
    return t


def camel(name: str) -> str:
    parts = name.split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def pascal(name: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in name.split("_"))


def cap(name: str) -> str:
    return name[:1].upper() + name[1:]


def ident(name: str) -> str:
    return name + "_" if name in KEYWORDS else name


