class Typer:
    def __init__(self, spec: dict):
        self.schemas = spec["components"]["schemas"]
        self.enum_schemas = {
            n for n, s in self.schemas.items() if s.get("type") != "object" and "enum" in s
        }

    def nonnull(self, s: dict) -> list:
        key = "anyOf" if "anyOf" in s else "oneOf"
        return [v for v in s[key] if v.get("type") != "null"]

    def jtype(self, s: dict) -> str:
        if "$ref" in s:
            n = s["$ref"].split("/")[-1]
            return "String" if n in self.enum_schemas else n
        if "anyOf" in s or "oneOf" in s:
            vs = self.nonnull(s)
            return self.jtype(vs[0]) if len(vs) == 1 else "Object"
        if "allOf" in s:
            return "Object"
        t = s.get("type")
        if t == "string":
            return "String"
        if t == "integer":
            return "Long"
        if t == "number":
            return "Double"
        if t == "boolean":
            return "Boolean"
        if t == "array":
            return "List<%s>" % (self.jtype(s["items"]) if "items" in s else "Object")
        if t == "object":
            ap = s.get("additionalProperties")
            if isinstance(ap, dict) and ap and not s.get("properties"):
                return "Map<String, %s>" % self.jtype(ap)
            return "Map<String, Object>"
        return "Object"

    def unwrap(self, s: dict) -> dict:
        """The single non-null variant of a nullable schema, else the schema."""
        if "anyOf" in s or "oneOf" in s:
            vs = self.nonnull(s)
            if len(vs) == 1:
                return {**{k: v for k, v in s.items() if k not in ("anyOf", "oneOf")}, **vs[0]}
        return s


def setter_prim(jt: str) -> str:
    return {"Long": "long", "Double": "double", "Boolean": "boolean"}.get(jt, jt)


def is_date_string(t: Typer, s: dict) -> bool:
    u = t.unwrap(s)
    return u.get("type") == "string" and (u.get("pattern") == DATE_PATTERN or u.get("format") == "date")


def is_since_string(t: Typer, name: str, s: dict) -> bool:
    u = t.unwrap(s)
    return u.get("type") == "string" and not is_date_string(t, s) and (name == "since" or name.endswith("Since")) and "pattern" not in u


def enum_values(t: Typer, s: dict) -> list:
    u = t.unwrap(s)
    if "enum" in u:
        return u["enum"]
    if u.get("type") == "array" and "enum" in u.get("items", {}):
        return u["items"]["enum"]
    return []


def prop_doc(t: Typer, s: dict) -> str:
    d = jd(s.get("description") or t.unwrap(s).get("description"), 300)
    vals = enum_values(t, s)
    if vals:
        shown = ", ".join(str(v) for v in vals[:12]) + (", ..." if len(vals) > 12 else "")
        d = (d + " " if d else "") + "One of: " + shown + "."
    return d or "The " + "value."


