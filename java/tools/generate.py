def setter_methods(t: Typer, name: str, s: dict, builder: str, store: str) -> str:
    """Builder setter(s) for one property. `store(valueExpr)` is the statement body template."""
    jt = t.jtype(s)
    n = ident(name)
    doc = prop_doc(t, s)
    out = []

    def one(param_type: str, expr: str, extra_doc: str = "") -> None:
        out.append(
            f"        /**\n         * {doc}{extra_doc}\n         *\n         * @param value the value\n         * @return this builder\n         */\n"
            f"        public {builder} {n}({param_type} value) {{\n            {store.format(f=name, v=expr)}\n            return this;\n        }}\n"
        )

    if jt in ("Long", "Double", "Boolean"):
        one(setter_prim(jt), "value")
    elif jt.startswith("List<"):
        inner = jt[5:-1]
        one(jt, "value == null ? null : Collections.unmodifiableList(new ArrayList<%s>(value))" % inner)
        if inner == "String":
            one("String...", "value == null ? null : Collections.unmodifiableList(new ArrayList<String>(Arrays.asList(value)))")
    else:
        one(jt, "value")
    if jt == "String" and is_date_string(t, s):
        one("LocalDate", "value == null ? null : value.toString()")
    if jt == "String" and is_since_string(t, name, s):
        one("Instant", "value == null ? null : DateTimeFormatter.ISO_INSTANT.format(value)")
    return "\n".join(out)


