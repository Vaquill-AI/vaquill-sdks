"""Regenerate ``src/vaquill/types/`` from the repository's ``openapi/vaquill-us.json``.

Run ``.venv/bin/python scripts/gen_models.py`` (``--check`` fails on drift instead of writing).

datamodel-code-generator does the schema walk. This script then post-processes the tree so the
models follow the SDK contract (PRD 8.2):

* every model derives from ``VaquillModel`` (extra members kept, camelCase wire aliases), and a
  model that is the body of a successful response derives from ``ResponseModel``, which owns
  ``credits_consumed``;
* every enum-typed field accepts a value the SDK has never seen (``lenient_validator``), and every
  ``Literal`` also accepts any other string, so a server that adds a value never raises here;
* value constraints (``ge``, ``max_length``, ``pattern`` ...) are dropped from the models: a
  response must not fail to parse because the server's range grew.
"""

from __future__ import annotations

import argparse
import ast
import json
import subprocess
import sys
import tempfile
from pathlib import Path

import black

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT.parent / "openapi" / "vaquill-us.json"
OUT = ROOT / "src" / "vaquill" / "types"

CODEGEN_ARGS = [
    "--input-file-type", "openapi",
    "--output-model-type", "pydantic_v2.BaseModel",
    "--base-class", "vaquill._response.VaquillModel",
    "--snake-case-field",
    "--use-annotated",
    "--field-constraints",
    "--use-union-operator",
    "--use-standard-collections",
    "--target-python-version", "3.11",
    "--naming-strategy", "parent-prefixed",
    "--output-datetime-class", "datetime",
    "--reuse-model",
    "--disable-timestamp",
    "--formatters", "builtin",
]  # fmt: skip

CONSTRAINT_KEYWORDS = {
    "ge", "gt", "le", "lt", "min_length", "max_length", "pattern", "multiple_of",
    "min_items", "max_items",
}  # fmt: skip
HEADER = (
    "# generated by scripts/gen_models.py from openapi/vaquill-us.json. Do not edit.\n"
    "# pyright: basic, reportAssignmentType=false\n"
    "# ruff: noqa\n"
)


def response_roots(spec: dict[str, object]) -> set[str]:
    """Schema names that are the JSON body of a 2xx response."""
    roots: set[str] = set()
    paths: dict[str, dict[str, dict[str, object]]] = spec["paths"]  # type: ignore[assignment]
    for item in paths.values():
        for op in item.values():
            responses: dict[str, dict[str, object]] = op.get("responses", {})  # type: ignore[assignment]
            for status, resp in responses.items():
                if not status.startswith("2"):
                    continue
                content: dict[str, dict[str, dict[str, str]]] = resp.get("content", {})  # type: ignore[assignment]
                ref = content.get("application/json", {}).get("schema", {}).get("$ref")
                if ref:
                    roots.add(ref.rsplit("/", 1)[-1])
    return roots


def _name(name: str) -> ast.Name:
    return ast.Name(id=name, ctx=ast.Load())


class Lenient(ast.NodeTransformer):
    def __init__(self, enums: set[str]) -> None:
        self.enums = enums

    def visit_Name(self, node: ast.Name) -> ast.AST:
        if node.id not in self.enums:
            return node
        # Annotated[E | str, lenient_validator(E)]
        union = ast.BinOp(left=_name(node.id), op=ast.BitOr(), right=_name("str"))
        validator = ast.Call(func=_name("lenient_validator"), args=[_name(node.id)], keywords=[])
        return ast.Subscript(
            value=_name("Annotated"),
            slice=ast.Tuple(elts=[union, validator], ctx=ast.Load()),
            ctx=ast.Load(),
        )

    def visit_Subscript(self, node: ast.Subscript) -> ast.AST:
        if isinstance(node.value, ast.Name) and node.value.id == "Literal":
            return ast.BinOp(left=node, op=ast.BitOr(), right=_name("str"))
        return self.generic_visit(node)


class Cleanup(ast.NodeTransformer):
    def visit_Call(self, node: ast.Call) -> ast.AST:
        self.generic_visit(node)
        if isinstance(node.func, ast.Name) and node.func.id == "Field":
            node.keywords = [k for k in node.keywords if k.arg not in CONSTRAINT_KEYWORDS]
        return node


def _is_enum(node: ast.ClassDef) -> bool:
    return any(
        isinstance(b, ast.Name) and b.id in {"Enum", "StrEnum", "IntEnum"} for b in node.bases
    )


def postprocess(source: str, roots: set[str]) -> str:
    tree = ast.parse(source)
    enums = {n.name for n in tree.body if isinstance(n, ast.ClassDef) and _is_enum(n)}
    lenient, cleanup = Lenient(enums), Cleanup()
    body: list[ast.stmt] = []
    for node in tree.body:
        if isinstance(node, ast.ImportFrom) and node.module == "vaquill._response":
            node = ast.ImportFrom(
                module="_response",
                names=[
                    ast.alias(n) for n in ("ResponseModel", "VaquillModel", "lenient_validator")
                ],
                level=2,
            )
        elif isinstance(node, ast.ImportFrom) and node.module == "typing":
            have = {a.name for a in node.names}
            node.names += [ast.alias(n) for n in ("Annotated", "Literal") if n not in have]
        elif isinstance(node, ast.ClassDef) and not _is_enum(node):
            for base in node.bases:
                if isinstance(base, ast.Name) and base.id == "VaquillModel" and node.name in roots:
                    base.id = "ResponseModel"
            if node.name in roots:  # the base class owns credits_consumed
                node.body = [
                    s
                    for s in node.body
                    if not (
                        isinstance(s, ast.AnnAssign)
                        and isinstance(s.target, ast.Name)
                        and s.target.id == "credits_consumed"
                    )
                ] or [ast.Pass()]
            for stmt in node.body:
                if isinstance(stmt, ast.AnnAssign):
                    stmt.annotation = lenient.visit(stmt.annotation)
                    cleanup.visit(stmt)
        body.append(node)
    tree.body = body
    ast.fix_missing_locations(tree)
    text = ast.unparse(tree)
    text = black.format_str(text, mode=black.Mode(line_length=100))
    return HEADER + text


def init_source(source: str) -> str:
    names = sorted(
        n.name
        for n in ast.parse(source).body
        if isinstance(n, ast.ClassDef) and not n.name.startswith("_")
    )
    lines = ["# generated by scripts/gen_models.py. Do not edit.", "# ruff: noqa", ""]
    lines += ['"""Typed request and response models generated from the OpenAPI document."""', ""]
    lines += ["from ._models import ("]
    lines += [f"    {n}," for n in names] + [")", "", "__all__ = ["]
    lines += [f'    "{n}",' for n in names] + ["]", ""]
    return "\n".join(lines)


def generate(out_dir: Path) -> None:
    spec = json.loads(SPEC.read_text())
    with tempfile.TemporaryDirectory() as tmp:
        raw = Path(tmp) / "models.py"
        subprocess.run(
            [sys.executable, "-m", "datamodel_code_generator", "--input", str(SPEC),
             "--output", str(raw), *CODEGEN_ARGS],
            check=True,
            capture_output=True,
        )  # fmt: skip
        models = postprocess(raw.read_text(), response_roots(spec))
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "_models.py").write_text(models)
    (out_dir / "__init__.py").write_text(init_source(models))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if committed files differ")
    args = parser.parse_args()
    if not args.check:
        generate(OUT)
        return 0
    with tempfile.TemporaryDirectory() as tmp:
        generate(Path(tmp))
        stale = [f.name for f in Path(tmp).iterdir() if (OUT / f.name).read_text() != f.read_text()]
    if stale:
        print(f"types/ is stale ({', '.join(stale)}). Run scripts/gen_models.py.")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
