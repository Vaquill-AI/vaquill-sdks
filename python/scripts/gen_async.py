"""Derive the async resources in ``src/vaquill/resources/_async/`` from the sync ones.

The sync classes in ``src/vaquill/resources/*.py`` are the single hand-written definition. This
"unasync" step rewrites them mechanically:

* ``SyncX`` becomes ``AsyncX`` (resources, base class, paginator);
* every method except ``iter_*`` becomes ``async def``, and so does the nested ``fetch``;
* calls on ``self._client.request`` and ``self._client.raw_request`` are awaited;
* imports move one package level down.

Run ``.venv/bin/python scripts/gen_async.py`` (``--check`` fails on drift instead of writing).
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "vaquill" / "resources"
OUT = SRC / "_async"
SKIP = {"__init__.py", "_base.py"}
HEADER = "# generated by scripts/gen_async.py from the sync module of the same name. Do not edit.\n"


def unasync(source: str) -> str:
    text = re.sub(
        r"\bSync(Resource|Paginator|Boards|Credits|Pricing|SessionLaws|Statutes|Watches)\b",
        r"Async\1",
        source,
    )
    text = re.sub(r"^    def (?!iter_)(\w+)\(", r"    async def \1(", text, flags=re.M)
    text = text.replace("        def fetch(", "        async def fetch(")
    text = re.sub(
        r"(\w+ = |return )self\._client\.(request|raw_request)\(", r"\1await self._client.\2(", text
    )
    text = text.replace("from .._pagination", "from ..._pagination")
    text = text.replace("from ..types", "from ...types")
    text = text.replace("from ._base", "from .._base")
    return HEADER + text


def ruff_format(text: str) -> str:
    """Sort imports, then format, with the project's ruff settings."""
    for args in (["check", "--select", "I", "--fix-only"], ["format"]):
        text = subprocess.run(
            [sys.executable, "-m", "ruff", *args, "--stdin-filename", "x.py", "-"],
            input=text,
            capture_output=True,
            text=True,
            check=True,
            cwd=ROOT,
        ).stdout
    return text


def generate(out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    names = sorted(p.name for p in SRC.glob("*.py") if p.name not in SKIP)
    for name in names:
        (out_dir / name).write_text(ruff_format(unasync((SRC / name).read_text())))
    (out_dir / "__init__.py").write_text(HEADER)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if not args.check:
        generate(OUT)
        return 0
    with tempfile.TemporaryDirectory() as tmp:
        generate(Path(tmp))
        stale = [
            f.name
            for f in Path(tmp).iterdir()
            if not (OUT / f.name).exists() or (OUT / f.name).read_text() != f.read_text()
        ]
    if stale:
        print(f"resources/_async is stale ({', '.join(stale)}). Run scripts/gen_async.py.")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
