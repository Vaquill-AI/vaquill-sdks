// Writes src/schemas.ts: one readable named type per entry of components.schemas in
// ../openapi/vaquill-us.json, as `export type X = components["schemas"]["X"]`.
//
// Names that collide with an export the package already has (error classes, Transport, ...)
// are emitted with a `Schema` suffix, and the list is printed. Schemas that the pruned
// src/_generated/api.d.ts does not carry (unreachable from any operation) cannot be aliased;
// they are listed in the file header and checked by test/hardening-resources.test.ts.
// Run via `npm run gen:aliases` after `npm run gen`.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const spec = JSON.parse(readFileSync("../openapi/vaquill-us.json", "utf8"));
const api = readFileSync("src/_generated/api.d.ts", "utf8");

// The schema keys api.d.ts actually exposes under components["schemas"].
const block = api.slice(api.indexOf("export interface components"));
const present = new Set([...block.matchAll(/^\s*"([^"]+)":/gm)].map((m) => m[1]));

// Everything the package entry point exports by hand (src/index.ts re-exports these files).
const reserved = new Set(["components", "Vaquill", "VERSION", "default"]);
for (const file of [
  "client.ts", "errors.ts", "pagination.ts", "response.ts", "types.ts", "webhooks.ts",
  "version.ts", "resources/_batch.ts",
]) {
  const text = readFileSync(`src/${file}`, "utf8");
  for (const m of text.matchAll(/^export\s+(?:abstract\s+)?(?:declare\s+)?(?:class|interface|type|const|function|enum)\s+([A-Za-z0-9_$]+)/gm)) {
    reserved.add(m[1]);
  }
}
for (const file of readdirSync("src/resources")) {
  const text = readFileSync(`src/resources/${file}`, "utf8");
  for (const m of text.matchAll(/^export\s+(?:class|interface|type|const|function)\s+([A-Za-z0-9_$]+)/gm)) {
    reserved.add(m[1]);
  }
}

const names = Object.keys(spec.components.schemas).sort();
const missing = names.filter((n) => !present.has(n));
const collisions = [];
const lines = [];
for (const n of names) {
  if (!present.has(n)) continue;
  let alias = n.replace(/[^A-Za-z0-9_$]/g, "_");
  if (reserved.has(alias)) {
    collisions.push(`${n} -> ${alias}Schema`);
    alias = `${alias}Schema`;
  }
  lines.push(`export type ${alias} = components["schemas"]["${n}"];`);
}

const header = [
  "// biome-ignore-all lint: generated\n// biome-ignore-all format: generated\n// GENERATED by scripts/gen-schema-aliases.mjs from openapi/vaquill-us.json. Do not edit.",
  "// Run `npm run gen:aliases` after `npm run gen`. test/hardening-resources.test.ts fails on drift.",
  "//",
  `// ${names.length} schemas in the spec; ${lines.length} aliased.`,
  `// Not aliased (pruned from src/_generated/api.d.ts, unreachable from any operation): ${missing.join(", ") || "none"}.`,
  `// Aliased under a "Schema" suffix because the name is already exported by the package: ${collisions.join(", ") || "none"}.`,
  "",
  'import type { components } from "./_generated/api.js";',
  "",
];
writeFileSync("src/schemas.ts", `${header.join("\n")}${lines.join("\n")}\n`);
console.log(`wrote src/schemas.ts: ${lines.length} aliases, ${missing.length} unreachable, ${collisions.length} renamed`);
if (collisions.length) console.log(collisions.join("\n"));
