#!/usr/bin/env python3
"""Generate src/main/kotlin/ai/vaquill/sdk/models/Models.kt from openapi/vaquill-us.json.

Usage:
    python3 tools/generate_models.py          # rewrite Models.kt
    python3 tools/generate_models.py --check  # exit 1 when Models.kt is stale (drift check)

Mapping rules (response models are deliberately lenient so a new server value never breaks a call):
  * enums become String (the allowed values stay in the KDoc);
  * integer -> Long, number -> Double, free-form objects -> JsonObject;
  * a union of several non-null types -> JsonElement;
  * a property that is required and not nullable has no default; every other property defaults to
    null (or to the spec default for scalars and empty lists).
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT.parent / "openapi" / "vaquill-us.json"
OUT = ROOT / "src/main/kotlin/ai/vaquill/sdk/models/Models.kt"

KEYWORDS = {
    "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in",
    "interface", "is", "null", "object", "package", "return", "super", "this", "throw", "true",
    "try", "typealias", "typeof", "val", "var", "when", "while",
}


def clean(text: str, limit: int = 420) -> str:
    text = (text or "").replace("—", " - ").replace("–", " - ")
    text = text.split("\n\n")[0].replace("\n", " ").strip()
    text = text.replace("*/", "* /").replace("/*", "/ *")
    text = re.sub(r"\s+", " ", text)
    if len(text) > limit:
        text = text[: limit - 3].rstrip() + "..."
    return text


def kdoc(text: str, indent: str) -> str:
    text = clean(text)
    return f"{indent}/** {text} */\n" if text else ""


def ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def kt_type(p: dict, schemas: dict) -> tuple[str, bool]:
    """Return (kotlin type without the trailing ?, nullable)."""
    if "$ref" in p:
        name = ref_name(p["$ref"])
        target = schemas[name]
        return ("String" if target.get("type") == "string" else name), False
    if "anyOf" in p:
        members = p["anyOf"]
        non_null = [m for m in members if m.get("type") != "null"]
        nullable = len(non_null) != len(members)
        if len(non_null) == 1:
            t, n = kt_type(non_null[0], schemas)
            return t, nullable or n
        return "JsonElement", nullable
    if "oneOf" in p or "allOf" in p:
        return "JsonElement", False
    t = p.get("type")
    if t == "string":
        return "String", False
    if t == "integer":
        return "Long", False
    if t == "number":
        return "Double", False
    if t == "boolean":
        return "Boolean", False
    if t == "array":
        inner, inner_null = kt_type(p.get("items", {}), schemas)
        return f"List<{inner}{'?' if inner_null else ''}>", False
    if t == "object":
        return "JsonObject", False
    return "JsonElement", False


def default_for(p: dict, kt: str) -> str:
    d = p.get("default")
    if d is None:
        return "null"
    if kt == "String" and isinstance(d, str):
        return json.dumps(d).replace("$", "\\$")
    if kt == "Boolean" and isinstance(d, bool):
        return "true" if d else "false"
    if kt == "Long" and isinstance(d, int) and not isinstance(d, bool):
        return f"{d}L"
    if kt == "Double" and isinstance(d, (int, float)) and not isinstance(d, bool):
        return repr(float(d))
    if kt.startswith("List<") and d == []:
        return "emptyList()"
    return "null"


def generate() -> str:
    spec = json.loads(SPEC.read_text())
    schemas = spec["components"]["schemas"]
    out: list[str] = []
    out.append(
        "// GENERATED by tools/generate_models.py from openapi/vaquill-us.json. Do not edit by hand.\n"
        "// Regenerate with: python3 tools/generate_models.py (CI drift check: --check).\n"
        "@file:Suppress(\"unused\", \"RedundantVisibilityModifier\")\n\n"
        "package ai.vaquill.sdk.models\n\n"
        "import kotlinx.serialization.Serializable\n"
        "import kotlinx.serialization.json.JsonElement\n"
        "import kotlinx.serialization.json.JsonObject\n"
    )
    for name in sorted(schemas):
        s = schemas[name]
        if s.get("type") == "string" and "enum" in s:
            vals = ", ".join(json.dumps(v) for v in s["enum"])
            out.append(f"\n{kdoc(s.get('description', 'Allowed values.'), '')}public object {name}s {{")
            out.append("    /** Every value the contract currently lists. The server may add more. */")
            out.append(f"    public val values: List<String> = listOf({vals})")
            for v in s["enum"]:
                const = re.sub(r"[^A-Za-z0-9]+", "_", v).upper().strip("_") or "EMPTY"
                if const[0].isdigit():
                    const = "V_" + const
                out.append(f"    public const val {const}: String = {json.dumps(v)}")
            out.append("}\n")
            continue
        props = s.get("properties", {})
        required = set(s.get("required", []))
        out.append(f"\n{kdoc(s.get('description', name), '')}@Serializable")
        if not props:
            out.append(f"public class {name}")
            continue
        out.append(f"public data class {name}(")
        for pname, p in props.items():
            kt, nullable = kt_type(p, schemas)
            is_req = pname in required
            ident = pname + "_" if pname in KEYWORDS else pname
            doc = clean(p.get("description", ""), 300)
            if "enum" in p or any("enum" in m for m in p.get("anyOf", [])):
                pass
            if doc:
                out.append(f"    /** {doc} */")
            if ident != pname:
                out.append(f'    @kotlinx.serialization.SerialName("{pname}")')
            if is_req and not nullable:
                out.append(f"    public val {ident}: {kt},")
            else:
                dflt = default_for(p, kt) if not nullable else "null"
                if dflt == "null":
                    out.append(f"    public val {ident}: {kt}? = null,")
                else:
                    out.append(f"    public val {ident}: {kt} = {dflt},")
        out.append(")")
    return "\n".join(out) + "\n"


def main() -> int:
    text = generate()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("Models.kt is stale: run python3 tools/generate_models.py", file=sys.stderr)
            return 1
        print("Models.kt is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
